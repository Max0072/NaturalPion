"""Write docs/paper/latex/numbers.tex: one \\pndef per \\pn{key}{format} used in docs/paper/latex/*.tex, its value from
docs/paper/numbers.json.

    python scripts/analysis/paper_numbers.py && python scripts/analysis/render_tex.py && (cd docs/paper/latex && tectonic main.tex)

Keys and Python format specs as in numbers.json, written as LaTeX (a `%` in a format is written `\\%` in the source). A key without a value is not defined, and \\pn prints it as
**[key?]**, so a gap is visible in the PDF and cannot pass for a number.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEX = ROOT / "docs/paper/latex"
nums = json.load(open(ROOT / "docs/paper/numbers.json"))


def as_tex(v, fmt: str) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    out = format(v, fmt) if fmt else (f"{v:.4g}" if isinstance(v, float) else str(v))
    m = re.fullmatch(r"([+-]?[0-9.]+)e([+-])0*([0-9]+)", out)
    if m:                                                       # 4.2e-06 -> 4.2 \cdot 10^{-6}
        exp = ("-" if m.group(2) == "-" else "") + m.group(3)
        mant = m.group(1)
        if mant.lstrip("+-") == "1" and exp != "0":
            return f"\\ensuremath{{{mant[:-1] if mant[0] in '+-' else ''}10^{{{exp}}}}}"
        return f"\\ensuremath{{{mant} \\cdot 10^{{{exp}}}}}"
    out = out.replace("%", "\\%").replace(",", "\\,")
    if out[:1] in "+-":
        return f"\\ensuremath{{{out}}}"
    return out


def main():
    uses = set()
    for f in TEX.glob("*.tex"):
        if f.name == "numbers.tex":
            continue
        text = re.sub(r"(?<!\\)%.*", "", f.read_text())                       # drop comments
        uses |= set(re.findall(r"\\pn\{([^}]*)\}\{((?:[^{}\\]|\\%)*)\}", text))
    lines = ["% Generated by scripts/analysis/render_tex.py from docs/paper/numbers.json. Do not edit."]
    gaps, unknown = [], []
    for key, fmt_tex in sorted(uses):
        if key not in nums:
            unknown.append(key)
            continue
        if nums[key] is None:
            gaps.append(key)
            continue
        lines.append(f"\\pndef{{{key}}}{{{fmt_tex}}}{{{as_tex(nums[key], fmt_tex.replace(chr(92) + '%', '%'))}}}")
    (TEX / "numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"{len(uses)} uses; {len(gaps)} gaps {sorted(gaps)}; {len(unknown)} unknown keys {sorted(unknown)}")


if __name__ == "__main__":
    main()
